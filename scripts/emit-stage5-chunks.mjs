#!/usr/bin/env node
/* Splits Stage 5 out of the generated content migration, one file per step.
 *
 *   node scripts/emit-stage5-chunks.mjs
 *
 * Stage 5 carries 60 Markdown Learn modules, which makes
 * 12_journey_content_lt_bachelor.sql far too large to hand to a migration tool
 * in one piece. Stages 1 to 4 are already applied and unchanged, so only Stage 5
 * needs to travel.
 *
 * Each chunk is the SAME upsert the full migration performs, restricted to one
 * step, so applying every chunk in order is equivalent to applying Stage 5 from
 * the full file — and a failure names the step it happened on instead of
 * aborting a single enormous statement. That is the rule the journey migrations
 * already follow: split so a failure can be isolated in one run.
 *
 * Reads the payload out of the generated migration rather than rebuilding it,
 * so a chunk can never describe a different journey from the file it came from.
 */

import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { resolve } from "node:path";

const SRC = resolve("supabase/migrations/journey/12_journey_content_lt_bachelor.sql");
const OUT_DIR = resolve("supabase/migrations/journey/stage5");
const COUNTRY = "LT";
const PLANS = ["self_service", "full_service"];

const sql = readFileSync(SRC, "utf8");
const payload = JSON.parse(
  /content {2}jsonb := '([\s\S]*?)'::jsonb;/.exec(sql)[1].replaceAll("''", "'"),
);

const stage = payload.stages.at(-1);
if (!/Arrival in Lithuania/i.test(stage.title)) {
  throw new Error(`expected Stage 5 last, found "${stage.title}"`);
}

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });

/* Chunk 00 creates or updates the stage itself, so the steps have a parent. */
const files = [];
const header = (n) => `-- Stage 5 chunk ${n} · generated by scripts/emit-stage5-chunks.mjs — do not hand-edit.\n`;

files.push([
  "00_stage",
  `${header("00 · the stage")}
do $s5$
declare v_plan text; v_stage uuid;
begin
foreach v_plan in array array[${PLANS.map(q).join(", ")}] loop
  select id into v_stage from public.journey_stages
   where country = ${q(COUNTRY)} and plan = v_plan and title = ${q(stage.title)} limit 1;
  if v_stage is null then
    insert into public.journey_stages (country, plan, sort_order, title, description, icon, tone, status, rules)
    values (${q(COUNTRY)}, v_plan, ${payload.stages.length - 1}, ${q(stage.title)}, ${q(stage.description ?? "")},
            ${q(stage.icon)}, ${q(stage.tone)}, ${q(stage.status)}, ${j(stage.rules)});
  else
    update public.journey_stages
       set sort_order = ${payload.stages.length - 1}, description = ${q(stage.description ?? "")},
           icon = ${q(stage.icon)}, tone = ${q(stage.tone)}, status = ${q(stage.status)}, rules = ${j(stage.rules)}
     where id = v_stage;
  end if;
end loop;
end $s5$;
`,
]);

stage.steps.forEach((step, i) => {
  const n = String(i + 1).padStart(2, "0");
  const blocks = step.blocks.map((b, bi) => `
      insert into public.journey_blocks (step_id, sort_order, kind, enabled, title, body, data, audience)
      values (v_step, ${bi}, ${q(b.kind)}, ${b.enabled}, ${q(b.title ?? "")}, ${q(b.body ?? "")}, ${j(b.data)}, 'student');`).join("");

  files.push([
    `${n}_${step.title.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "").slice(0, 40)}`,
    `${header(`${n} · ${step.title}`)}
do $s5$
declare v_plan text; v_stage uuid; v_step uuid;
begin
foreach v_plan in array array[${PLANS.map(q).join(", ")}] loop
  select id into v_stage from public.journey_stages
   where country = ${q(COUNTRY)} and plan = v_plan and title = ${q(stage.title)} limit 1;
  if v_stage is null then continue; end if;

  select id into v_step from public.journey_steps
   where stage_id = v_stage and title = ${q(step.title)} limit 1;

  if v_step is null then
    insert into public.journey_steps (stage_id, sort_order, title, description, status, required, rules)
    values (v_stage, ${i}, ${q(step.title)}, ${q(step.description)}, 'published', ${step.required}, ${j(step.rules)})
    returning id into v_step;
  else
    update public.journey_steps
       set sort_order = ${i}, description = ${q(step.description)}, status = 'published',
           required = ${step.required}, rules = ${j(step.rules)}
     where id = v_step;
  end if;

  /* Same tag the full migration uses. Deleting on a tag the blocks do not
     carry would match nothing, so re-running a chunk would append a second copy
     of every module instead of replacing them. Blocks an administrator added by
     hand carry no source tag and survive, exactly as in the full migration. */
  delete from public.journey_blocks where step_id = v_step and (data ->> 'source') = 'xlsx';
${blocks}
end loop;
end $s5$;
`,
  ]);
});

/* The last chunk archives any Stage 5 step the content no longer lists. Run it
   only after every step chunk, or it archives the ones not yet applied. */
files.push([
  "99_prune",
  `${header("99 · archive steps the content no longer lists")}
update public.journey_steps set status = 'archived'
 where stage_id in (
   select id from public.journey_stages
    where country = ${q(COUNTRY)} and title = ${q(stage.title)}
 )
   and status <> 'archived'
   and title not in (${stage.steps.map((s) => q(s.title)).join(", ")});

notify pgrst, 'reload schema';
`,
]);

let total = 0;
for (const [name, body] of files) {
  const path = `${OUT_DIR}/${name}.sql`;
  writeFileSync(path, body);
  total += body.length;
  console.log(`  ${(body.length / 1024).toFixed(1).padStart(6)} KB  ${name}.sql`);
}
console.log(`\n${files.length} chunks · ${(total / 1024).toFixed(1)} KB · ${stage.steps.length} steps · ${stage.steps.reduce((n, s) => n + s.blocks.length, 0)} blocks`);
console.log(`Written to ${OUT_DIR}`);
