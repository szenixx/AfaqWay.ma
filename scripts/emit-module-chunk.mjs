#!/usr/bin/env node
/* Emits the optional-module steps of one stage as a standalone migration.
 *
 *   node scripts/emit-module-chunk.mjs "migration Application Preparation"
 *
 * Stages 1 to 5 are already applied; only the module steps are new. Reads the
 * payload out of the generated content migration rather than rebuilding it, so
 * the chunk can never describe something the full file does not.
 *
 * The chunk is idempotent in the same way the full migration is: steps are
 * matched by title within the stage, so re-running updates instead of
 * duplicating, and a student's progress rows keep pointing at the same ids.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";

const STAGE_TITLE = process.argv[2] ?? "migration Application Preparation";
const SRC = resolve("supabase/migrations/journey/12_journey_content_lt_bachelor.sql");
const OUT = resolve("supabase/migrations/journey/21_sponsorship_module.sql");
const COUNTRY = "LT";
const PLANS = ["self_service", "full_service"];

const sql = readFileSync(SRC, "utf8");
const payload = JSON.parse(
  /content {2}jsonb := '([\s\S]*?)'::jsonb;/.exec(sql)[1].replaceAll("''", "'"),
);

const stage = payload.stages.find((s) => s.title === STAGE_TITLE);
if (!stage) throw new Error(`stage "${STAGE_TITLE}" not found`);

/* Only the module steps. Their sort_order is their real index in the stage, so
   they keep sitting after the Excel's own steps. */
const steps = stage.steps
  .map((step, index) => ({ step, index }))
  .filter(({ step }) => step.rules.module || step.rules.moduleOf);

if (!steps.length) throw new Error(`no module steps in "${STAGE_TITLE}"`);

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

const body = steps.map(({ step, index }) => `
  select id into v_step from public.journey_steps
   where stage_id = v_stage and title = ${q(step.title)} limit 1;

  if v_step is null then
    insert into public.journey_steps (stage_id, sort_order, title, description, status, required, rules)
    values (v_stage, ${index}, ${q(step.title)}, ${q(step.description)}, 'published', ${step.required}, ${j(step.rules)})
    returning id into v_step;
  else
    update public.journey_steps
       set sort_order = ${index}, description = ${q(step.description)}, status = 'published',
           required = ${step.required}, rules = ${j(step.rules)}
     where id = v_step;
  end if;
`).join("");

writeFileSync(OUT, `-- 21 · Optional Sponsorship module for "${STAGE_TITLE}".
--
-- Generated by scripts/emit-module-chunk.mjs — do not hand-edit. The steps are
-- declared in scripts/journey-modules.mjs and are part of the normal import, so
-- re-running scripts/import-journey.mjs keeps them rather than archiving them.
--
-- Steps: ${steps.length} (1 container + ${steps.length - 1} children)
--
-- These steps exist for every student but stay hidden, uncounted and inert
-- until the student switches the module on; enablement is one flag on the
-- container's own journey_progress row, so nothing here is per-student.
--
-- Learn content is deliberately empty: administrators populate it from the
-- Journey Manager, and nothing in the platform needs it to be there first.

do $mod$
declare
  v_plan  text;
  v_stage uuid;
  v_step  uuid;
begin
foreach v_plan in array array[${PLANS.map(q).join(", ")}] loop

  select id into v_stage from public.journey_stages
   where country = ${q(COUNTRY)} and plan = v_plan and title = ${q(stage.title)} limit 1;
  if v_stage is null then continue; end if;
${body}
end loop;
end $mod$;

notify pgrst, 'reload schema';
`);

console.log(`${steps.length} module steps → ${OUT}`);
for (const { step, index } of steps) {
  const kind = step.rules.module ? "container" : `child of ${step.rules.moduleOf}`;
  console.log(`  ${String(index).padStart(2)}  ${step.title}  (${kind})`);
}
